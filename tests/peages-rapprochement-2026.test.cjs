'use strict';
const assert = require('node:assert/strict');
const { test } = require('node:test');
const { spawnSync } = require('node:child_process');
const path = require('node:path');
const script = path.resolve(__dirname, '../scripts/audit-rapprochement-peages.cjs');
test('rapprochement : bilan complet et ecarts Beuzeville visibles', () => {
  const run = spawnSync(process.execPath, [script], { encoding: 'utf8', maxBuffer: 10 * 1024 * 1024 });
  assert.equal(run.status, 0, run.stderr);
  const r = JSON.parse(run.stdout);
  assert.equal(r.compared_overlay_pairs, r.identical + r.divergent + r.ambiguous + r.not_matched);
  assert.equal(r.divergent, r.divergences.length);
  assert.ok(r.identical > 0);
  assert.ok(r.not_matched > 0);
  assert.equal(r.unmatched_origins.reduce((n, x) => n + x.count, 0), r.not_matched);
  assert.equal(r.unmatched_origin_count, r.unmatched_origins.length);
  assert.equal(Object.values(r.unmatched_classification).reduce((a, b) => a + b, 0), r.not_matched);
  assert.equal(r.unmatched_classification.both_endpoints_present_pair_missing, 672);
  assert.equal(r.missing_pair_origins.reduce((n, x) => n + x.count, 0), 672);
  assert.equal(r.missing_pair_details.length, 672);
  assert.equal(r.unmatched_details.length, r.not_matched);
  assert.equal(r.unmatched_details.length, 7251);
  for (const [category, count] of Object.entries(r.unmatched_classification)) assert.equal(r.unmatched_details.filter(x => x.classification === category).length, count);
  assert.equal(r.missing_pair_unique_gates, 148);
  assert.ok(r.missing_name_counts.length > 0);
  assert.ok(r.missing_name_counts.every((x, i, arr) => x.gate && x.occurrences > 0 && (i === 0 || arr[i - 1].occurrences >= x.occurrences)));
  assert.ok(r.missing_pair_details.every(x => x.origin && x.destination && Number.isFinite(x.overlay_class1) && Number.isFinite(x.overlay_class2)));
  assert.ok(r.missing_pair_examples.length > 0 && r.missing_pair_examples.length <= 30);
  assert.ok(r.missing_pair_origins.every((x, i, arr) => i === 0 || arr[i - 1].count >= x.count));
  assert.equal(r.unmatched_classification.one_endpoint_missing, 4397);
  assert.equal(r.unmatched_classification.both_endpoints_missing, 2182);
  assert.ok(r.unmatched_origins.every((x, i, arr) => i === 0 || arr[i - 1].count >= x.count));
  assert.ok(r.divergences.every(d => Number.isFinite(d.base_class1) && Number.isFinite(d.overlay_class2)));
  assert.equal(r.audit, 'rapprochement des noms normalises, pas certification officielle');
});
