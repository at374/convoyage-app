// node tests/planning-calendrier.test.js — deterministic mock tests, no external service.
'use strict';
const assert=require('node:assert/strict');
global.CPGeo={coordonnees:(m,w)=>m[w],routeKm:(a,b)=>Math.abs(a.lat-b.lat)*10};
global.CPCalc={liaison:km=>({km,heures:km/50,cout:km/10}),rentabiliteComplete:m=>({connu:true,net:m.fee,heures:1})};
global.CPRetours={domicile:()=>({lat:0,nom:'domicile'}),debut:m=>Date.parse(m.pickup_start),fin:m=>({t:Date.parse(m.delivery_end),estimee:false}),cle:m=>m.id};
const {planifier}=require('../planning.js');
const mission=(kind,id,start,end,platform='Otoqi')=>({kind,id,platform,fee:100,pickup_start:start,delivery_end:end,origin:{lat:0},destination:{lat:0}});
const run=(missions,start,options={})=>planifier(missions,{}, {debut:Date.parse(start),jours:2,nuits_max:3,heureMin:null,...options});
const monday=mission('disponible','monday','2026-11-02T09:00:00Z','2026-11-02T10:00:00Z');
const accepted=mission('acceptee','accepted','2026-11-02T13:00:00Z','2026-11-02T14:00:00Z');
const original=JSON.stringify([monday,accepted]);
assert.equal(run([monday,accepted],'2026-11-02T06:00:00Z',{inclureAcceptees:true}).candidates,2);
const rest=run([monday,accepted],'2026-11-02T06:00:00Z',{joursReposHebdo:['mon'],inclureAcceptees:true});
assert.equal(rest.candidates,1);
assert.equal(rest.ancres,1);
assert.ok(rest.plans.length);
assert.equal(run([monday,accepted],'2026-11-02T06:00:00Z',{plateformesActives:['Hiflow'],inclureAcceptees:true}).candidates,1);
assert.equal(run([monday,accepted],'2026-11-02T06:00:00Z',{joursSansTravail:['2026-11-02'],inclureAcceptees:true}).candidates,1);
const night=mission('disponible','night','2026-11-02T22:30:00Z','2026-11-03T00:30:00Z');
assert.equal(run([night],'2026-11-02T06:00:00Z',{joursReposHebdo:['tue']}).candidates,0);
assert.equal(run([night],'2026-11-02T06:00:00Z',{joursSansTravail:['2026-11-03']}).candidates,0);
const afterSpring=mission('disponible','spring','2027-03-29T08:00:00Z','2027-03-29T09:00:00Z');
assert.equal(run([afterSpring],'2027-03-28T06:00:00Z',{jours:1}).candidates,0);
assert.equal(run([afterSpring],'2027-03-28T06:00:00Z',{jours:2}).candidates,1);
const afterAutumn=mission('disponible','autumn','2026-10-26T08:00:00Z','2026-10-26T09:00:00Z');
assert.equal(run([afterAutumn],'2026-10-25T06:00:00Z',{jours:1}).candidates,0);
assert.equal(run([afterAutumn],'2026-10-25T06:00:00Z',{jours:2}).candidates,1);
assert.equal(JSON.stringify([monday,accepted]),original,'must not modify missions');
console.log('Planning calendar: 12 assertions passed');
